test('every rule, flag and runner has a hit and a command that looks like one and is not', async () => {
  const keys = [...RULES.map(r => r.key), ...VALUE_FLAGS, ...PLAIN_FLAGS, ...RUNNERS, 'script']
  expect(new Set(keys).size).toBe(keys.length)
  const missing = keys.filter(key => !CASES.some(c => c[2] === key && c[1]) || !CASES.some(c => c[2] === key && !c[1]))
  expect(missing).toEqual([])
  const unknown = CASES.filter(c => !keys.includes(c[2])).map(c => c[2])
  expect(unknown).toEqual([])
})

// A hit that is one command alone, with no list, pipeline, shell or comment around it (what is added after a comment is a comment).
const single = CASES.filter(([command, isStanding]) => isStanding && !/&&|\|\||;|\||\n|#|\b(bash|sh|zsh) -/.test(command))

test('a standing command sent to the background, echoed, quoted or under timeout is not standing', async () => {
  expect(single.length).toBeGreaterThan(100)
  for (const [command] of single) {
    for (const changed of [`${command} &`, `echo ${command}`, `'${command}'`, `timeout 60 ${command}`])
      expect([changed, standingCommand(changed)]).toEqual([changed, false])
  }
})

test('a standing command after a cd stays standing and shows the same words', async () => {
  for (const [command] of single) expect([command, standingPart(`cd /x && ${command}`)]).toEqual([command, standingPart(command)])
})

test('standing: only a shell task with a standing command, whatever the description says', async () => {
  const task = (type: string, command?: string, description = 'Start dev server') => ({ id: 'b1', type, status: 'running', description, command })
  expect(standing(task('shell', 'npm run dev'))).toBe(true)
  for (const type of ['subagent', 'workflow', 'monitor', 'local_bash_next']) expect([type, standing(task(type, 'npm run dev'))]).toEqual([type, false])
  expect(standing(task('shell'))).toBe(false)
  expect(standing(task('shell', ''))).toBe(false)
  expect(standing(task('shell', 'gh pr checks 8 --watch', 'Watch the dev server'))).toBe(false)
})
